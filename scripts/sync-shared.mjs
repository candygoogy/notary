// Copies /shared/*.ts into every plugins/*/hooks/shared/ (mods can only import
// files inside their own plugin folder). `--check` fails if any copy drifted.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const isCheck = process.argv.includes('--check')
const HEADER = '// GENERATED by scripts/sync-shared.mjs from /shared. Do not edit here.\n'
const sources = readdirSync(join(root, 'shared')).filter(name => name.endsWith('.ts'))
const plugins = readdirSync(join(root, 'plugins'))
let drift = 0

for (const plugin of plugins) {
  const target = join(root, 'plugins', plugin, 'hooks', 'shared')
  mkdirSync(target, { recursive: true })
  for (const name of sources) {
    const wanted = HEADER + readFileSync(join(root, 'shared', name), 'utf8')
    const path = join(target, name)
    const actual = existsSync(path) ? readFileSync(path, 'utf8') : null
    if (actual === wanted) continue
    if (isCheck) {
      console.error(`drift: plugins/${plugin}/hooks/shared/${name}`)
      drift += 1
    } else {
      writeFileSync(path, wanted)
      console.log(`synced plugins/${plugin}/hooks/shared/${name}`)
    }
  }
}

process.exit(drift === 0 ? 0 : 1)
